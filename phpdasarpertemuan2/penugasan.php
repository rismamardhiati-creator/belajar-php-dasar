<?php
$a = 30;

// Operator Penugasan
$a += 5; // $a sekarang bernilai 20
echo $a . "<br>";

$a -= 3; // $a sekarang bernilai 11
echo $a . "<br>";

$a *= 2; // $a sekarang bernilai 32
echo $a . "<br>";

$a /= 4; // $a sekarang bernilai 8
echo $a . "<br>";

$a %= 5; // $a sekarang bernilai 2
echo $a . "<br>";
?>